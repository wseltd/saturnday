def _cmd_validate_plan(args: argparse.Namespace) -> int:
    """Execute the ``validate-plan`` subcommand."""
    _configure_logging(args)

    from .plan_parser import validate_plan
    plan_path = Path(args.plan)
    if not plan_path.exists():
        print(f"Error: Plan file not found: {plan_path}", file=sys.stderr)
        return 1

    try:
        raw = json.loads(plan_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    errors = validate_plan(raw)
    if errors:
        print("Plan validation failed:")
        for err in errors:
            print(f"  - {err}")
        return 1

    print("Plan is valid.")

    # Also run contract verification
    try:
        from saturnday.run.contract_checker import extract_contracts, verify_contracts
        from saturnday.plan_parser import load_plan
        plan = load_plan(plan_path)
        all_criteria: tuple[str, ...] = tuple(
            c for t in plan.tickets for c in t.acceptance_criteria
        )
        if all_criteria:
            contracts = extract_contracts(all_criteria)
            if contracts:
                results = verify_contracts(contracts, plan_path.parent)
                failed_results = [r for r in results if not r.verified]
                if failed_results:
                    print(f"\nContract verification: {len(failed_results)} issue(s)")
                    for r in failed_results:
                        print(f"  - {r.detail}")
                else:
                    print(f"\nContract verification: PASS ({len(results)} contract(s) verified)")
            else:
                print("\nContract verification: PASS (no verifiable contracts found)")
        else:
            print("\nContract verification: PASS (no acceptance criteria to verify)")
    except ImportError:
        pass
    except Exception as exc:
        print(f"\nContract verification failed: {exc}")

    interface_errors = _report_interface_contract(raw, getattr(args, "repo", "."))

    return 1 if interface_errors else 0


def _report_interface_contract(raw: dict, repo: str) -> int:
    """Print interface-contract findings and return the error count.

    IC-001 (duplicate provides) is an error; IC-002 (unresolvable verify_cmd
    tool) is a warning and never changes the exit code on its own.
    """
    try:
        from saturnday.interface_contract import check_interface_contract
    except ImportError:
        return 0

    try:
        findings = check_interface_contract(raw, Path(repo) if repo else None)
    except Exception as exc:
        print(f"\nInterface contract check failed: {exc}")
        return 0

    if not findings:
        print("\nInterface contract: PASS (no collisions or unresolved tools)")
        return 0

    errors = [f for f in findings if f.severity == "error"]
    warnings = [f for f in findings if f.severity != "error"]

    print(
        f"\nInterface contract: {len(errors)} error(s), {len(warnings)} warning(s)"
    )
    for finding in errors:
        print(f"  - {finding.format_line()}")
    for finding in warnings:
        print(f"  - {finding.format_line()}")

    return len(errors)


def _cmd_explain_failure(args: argparse.Namespace) -> int:
    """Execute the ``explain-failure`` subcommand.

    Detects the evidence type from directory contents and prints the
    appropriate human-readable report:
    - Run evidence: ledger-based failure report (existing behaviour)
    - Governance evidence: governance-report.md
    - Release evidence: summary.md
    """
    _configure_logging(args)

    evidence_dir = Path(args.output_dir).resolve()
    if not evidence_dir.is_dir():
        print(f"Error: evidence directory not found: {evidence_dir}", file=sys.stderr)
        return 1

    from .evidence_type import detect_evidence_type
    etype = detect_evidence_type(evidence_dir)

    if etype == "run":
        from .run.report import generate_failure_report
        try:
            report = generate_failure_report(args.output_dir)
            print(report)
        except FileNotFoundError as exc:
            print(f"Error: {exc}", file=sys.stderr)
            return 1
        return 0

    if etype == "governance":
        gov_report = evidence_dir / "governance-report.md"
        if gov_report.exists():
            print(gov_report.read_text(encoding="utf-8"))
            return 0
        gov_summary = evidence_dir / "summary.md"
