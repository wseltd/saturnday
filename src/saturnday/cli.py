def _bootstrap_baseline_if_missing(repo: Path, *, context: str = "hook install") -> None:
    """Fix A: seed a ratchet baseline at any governed-execution entrypoint.

    On a real existing non-green repository, without a baseline the
    ratchet branch in ``governance.py`` stays inert and every pre-existing
    finding reads as a fresh regression — blocking every commit AND every
    run-mode ticket that touches a file with pre-existing findings.

    This helper is called from the product's governed-execution entrypoints
    (hook install, run, resume, rerun-failed, rerun-remaining) so operators
    are bootstrapped on whichever one they happen to reach first.

    * Never overwrites an existing baseline.
    * Always visible to the operator — no silent seeding.
    * Always uses ``ratchet_mode="block_new"`` so new regressions still fail.

    ``context`` is a short string like ``"hook install"`` or ``"run"`` used
    only for operator-facing messaging so the surrounding command's output
    reads consistently.
    """
    baseline_path = repo / ".saturnday-baseline.json"
    if baseline_path.is_file():
        # On hook install we print an explicit "leaving untouched" line
        # because that command's entire job is setup.  On governed-run
        # entrypoints we stay silent if a baseline is already present —
        # the operator doesn't need a banner every invocation.
        if context == "hook install":
            print(
                f"Saturnday: baseline already present at {baseline_path.name} — "
                "leaving untouched."
            )
        return

    print(
        f"\nSaturnday: no baseline found — bootstrapping ratchet baseline "
        f"before {context} proceeds..."
    )
    print("  Capturing pre-existing findings as known debt.")
    print("  New findings introduced after this point will still block commits.")

    # Reuse the existing ``saturnday baseline generate`` implementation
    # verbatim — same scan, same fingerprints, same output format.
    bootstrap_args = argparse.Namespace(
        repo=str(repo),
        policy=None,
        output=str(baseline_path),
        enforcement_date="",
        ratchet_mode="block_new",
        # Logging flags the parser requires.
        verbose=False,
        quiet=False,
    )
    try:
        rc = _handle_baseline_generate(bootstrap_args)
    except Exception as exc:  # pragma: no cover — best effort
        print(
            f"Saturnday: baseline bootstrap failed: {exc}\n"
            "  You can retry later with: saturnday baseline generate --repo .",
        )
        return
    if rc != 0:
        print(
            "Saturnday: baseline bootstrap did not succeed (see messages above).\n"
            "  You can retry later with: saturnday baseline generate --repo ."
        )
        return
    print(
        "Saturnday: baseline bootstrap complete.  Review "
        f"{baseline_path.name} and commit it to version control so the "
        "whole team shares the same known-debt snapshot."
    )


# Back-compat alias: earlier Fix A shipped with this name.  External
# callers (tests, scripts) may still reference it — keep it working.
_bootstrap_baseline_on_hook_install = _bootstrap_baseline_if_missing


def _handle_hook(args: argparse.Namespace) -> int:
    """Install or uninstall the Saturnday pre-commit hook."""
    action = args.hook_action
    if not action:
        print("Usage: saturnday hook {install|uninstall}")
        return 2

    repo = Path(args.repo).resolve()
    hooks_dir = repo / ".git" / "hooks"

    if not (repo / ".git").is_dir():
        print(f"Error: {repo} is not a git repository.", file=sys.stderr)
        return 1

    hook_path = hooks_dir / "pre-commit"

    if action == "install":
        hooks_dir.mkdir(parents=True, exist_ok=True)
        # Fix H: render with absolute binary path at install time so the
        # hook doesn't depend on whatever ``saturnday`` happens to be on
        # ``PATH`` at commit time (pyenv shim, another venv, etc.).
        hook_content = _render_pre_commit_hook()
        # Check if a hook already exists
        if hook_path.is_file():
            content = hook_path.read_text(encoding="utf-8")
            if "saturnday" in content.lower():
                print(f"Saturnday hook already installed: {hook_path}")
                # Fix A: still bootstrap the baseline on a repeat install if
                # one is missing, so an operator who previously installed the
                # hook without a baseline is not silently left unbootstrapped.
                _bootstrap_baseline_if_missing(repo, context="hook install")
                return 0
            # Existing non-saturnday hook — don't overwrite
            print(f"Warning: existing pre-commit hook found at {hook_path}")
            print("Appending Saturnday governance check.")
            content += "\n" + hook_content
            hook_path.write_text(content, encoding="utf-8")
        else:
            hook_path.write_text(hook_content, encoding="utf-8")
        hook_path.chmod(0o755)
        print(f"Saturnday pre-commit hook installed: {hook_path}")
        print("Every commit will now be governance-checked.")
        # Fix A: bootstrap a ratchet baseline so pre-existing findings in
        # this repo become known legacy debt rather than fresh regressions
        # that block every commit.  Does nothing if a baseline is already
        # present — we never overwrite an operator's curated baseline.
        _bootstrap_baseline_if_missing(repo, context="hook install")
        return 0

    if action == "uninstall":
        if not hook_path.is_file():
            print("No pre-commit hook found.")
            return 0
        content = hook_path.read_text(encoding="utf-8")
        if "saturnday" not in content.lower():
            print("Pre-commit hook exists but is not from Saturnday. Not removing.")
            return 0
        # Fix H: the installed hook embeds an absolute binary path.  Render
        # with the currently resolved binary for the comparison so uninstall
        # from the same environment succeeds.  Cross-environment uninstall
        # (different venv) falls through to the "remove section" path.
        rendered = _render_pre_commit_hook()
        if content.strip() == rendered.strip():
            hook_path.unlink()
            print("Saturnday pre-commit hook removed.")
        else:
            cleaned = content.replace(rendered, "")
            hook_path.write_text(cleaned, encoding="utf-8")
            print("Saturnday section removed from pre-commit hook.")
        return 0

    print("Usage: saturnday hook {install|uninstall}")
    return 2


def _validate_policy(repo: Path) -> int:
    """Fix 53.c: validate .saturnday-policy.yaml and report errors."""
    policy_path = repo / ".saturnday-policy.yaml"
    if not policy_path.is_file():
        print(f"No policy file found: {policy_path}")
        return 0

    try:
        import yaml
        raw = yaml.safe_load(policy_path.read_text(encoding="utf-8")) or {}
    except Exception as exc:
        print(f"FAIL: cannot parse {policy_path}: {exc}")
        return 1

    errors: list[str] = []

    # Validate expected_findings
    ef = raw.get("expected_findings", [])
    if ef:
        if not isinstance(ef, list):
            errors.append("expected_findings must be a list")
        else:
            for i, entry in enumerate(ef):
                if not isinstance(entry, str):
                    errors.append(
                        f"expected_findings[{i}]: must be a string (finding kind), "
                        f"got {type(entry).__name__}: {str(entry)[:80]}"
                    )

    # Validate exemptions
    exemptions = raw.get("exemptions", [])
    if exemptions:
        if not isinstance(exemptions, list):
            errors.append("exemptions must be a list")
        else:
            for i, entry in enumerate(exemptions):
                if not isinstance(entry, dict):
                    errors.append(f"exemptions[{i}]: must be a dict, got {type(entry).__name__}")
                    continue
                if "check" not in entry:
                    errors.append(f"exemptions[{i}]: missing required field 'check'")
                if "reason" not in entry:
                    errors.append(f"exemptions[{i}]: missing recommended field 'reason'")
                pattern = entry.get("pattern", "") or entry.get("path", "")
                if pattern and not isinstance(pattern, str):
                    errors.append(f"exemptions[{i}]: pattern/path must be a string")

    # Validate waivers
    waivers = raw.get("waivers", [])
    if waivers:
        if not isinstance(waivers, list):
            errors.append("waivers must be a list")

    if errors:
        print(f"FAIL: {len(errors)} error(s) in {policy_path}:\n")
        for e in errors:
            print(f"  - {e}")
        return 1

    # Count entries
    n_ef = len(ef) if isinstance(ef, list) else 0
    n_ex = len(exemptions) if isinstance(exemptions, list) else 0
    n_w = len(waivers) if isinstance(waivers, list) else 0
    print(f"OK: {policy_path}")
    print(f"  expected_findings: {n_ef}")
    print(f"  exemptions: {n_ex}")
    print(f"  waivers: {n_w}")
    return 0


def _handle_baseline_generate(args) -> int:
    """Generate a baseline snapshot from current scan."""
    from .ratchet import (
        fingerprint_check_results,
        generate_baseline,
        save_baseline,
    )
    from .review import run_review
    from .shell_policy import run_shell

    repo = Path(args.repo).expanduser().resolve()
    if not (repo / ".git").exists():
        print(f"Not a git repository: {repo}", file=sys.stderr)
        return 2

    # Get repo SHA
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=str(repo), capture_output=True, text=True, check=True,
        )
        repo_sha = result.stdout.strip()
    except Exception:
        repo_sha = ""

    # Get all tracked files (any type).  Pre-fix this listed only
    # ``*.py`` and short-circuited on empty, which meant docs-heavy /
    # scaffold / pre-first-Python-file repos could never baseline the
    # repo-level and non-Python findings their pre-commit hook would
    # still block on (secrets in .md, missing README, missing LICENSE,
    # etc.).  The hook's enforcement surface (see
    # governance.run_governance_check → review.run_review) runs those
    # checks regardless of file type, so the baseline surface must be
    # at least as wide.
    try:
        result = subprocess.run(
            ["git", "ls-files"],
            cwd=str(repo), capture_output=True, text=True, check=True,
        )
        files = [f.strip() for f in result.stdout.strip().splitlines() if f.strip()]
    except Exception:
        files = []

    # An empty tracked set is a valid baseline input — repo-level
    # checks (``_check_license``, ``_check_readme``, etc.) fire in
    # ``run_review`` regardless of ``changed_files``, so a baseline
    # that captures just those findings is still useful.  Previously
    # the function aborted here, making hook bootstrap impossible on
    # minimal or scaffold-stage repos.  We now proceed and let
    # ``run_review`` decide what to capture.
    if files:
        print(f"Scanning {len(files)} files in {repo}...")
    else:
        print(
            f"Scanning repo-level checks in {repo} "
            f"(no tracked files — baseline will capture repo-level findings only)..."
        )

    import tempfile
    from .evidence import CheckResult
    from .policy_manifest import (
        RULE_IDS,
        default_policy,
        get_check_severity,
        load_policy,
        should_run_check,
    )

    # Load policy
    policy = default_policy()
    if args.policy:
        p = Path(args.policy)
        if p.exists():
            policy = load_policy(p)

    # Run review
    with tempfile.TemporaryDirectory() as tmpdir:
        review_result = run_review(
            repo, files, Path(tmpdir),
            run_shell_func=run_shell, timeout_s=30, strict=False,
        )

    # Convert to CheckResults
    check_results = []
    tools = review_result.get("tools", {})
    for check_name, tool_result in tools.items():
        if not should_run_check(policy, check_name):
            continue
        status = tool_result.get("status", "PASS")
        findings = tool_result.get("findings", [])
        if not isinstance(findings, list):
            findings = []
        severity = get_check_severity(policy, check_name)
        rule_id = RULE_IDS.get(check_name)

        normalized = []
        for f in findings:
            if isinstance(f, dict):
                normalized.append(f)
            elif isinstance(f, str):
                normalized.append({"message": f})

        cr = CheckResult(
            name=check_name,
            status="FAIL" if status == "FAIL" else "PASS",
            severity=severity,
            findings=normalized,
            files_checked=files,
            rule_id=rule_id,
        )
        check_results.append(cr)

    # Fingerprint and generate baseline
    fingerprints = fingerprint_check_results(check_results, repo)
    baseline = generate_baseline(
        fingerprints=fingerprints,
        repo_sha=repo_sha,
        enforcement_date=args.enforcement_date,
        ratchet_mode=args.ratchet_mode,
    )

    output = Path(args.output)
    save_baseline(output, baseline)

    print(f"Baseline generated: {output}")
    print(f"  Fingerprints: {len(fingerprints)}")
    print(f"  Repo SHA: {repo_sha[:12]}")
    print(f"  Ratchet mode: {args.ratchet_mode}")
    if args.enforcement_date:
        print(f"  Enforcement date: {args.enforcement_date}")
        # I.3: make the operator aware of what they just configured.
        # The deadline switches BOTH modes into legacy-blocking once the
        # date passes — the mode name does not override that.
        print(
            "    ↳ HARD DEADLINE: after this date, legacy (pre-existing) "
            "findings start failing the ratchet in addition to the normal "
            f"'{args.ratchet_mode}' behaviour."
        )
    else:
        # Docs-adjacent nudge: operator should know this is the "legacy
        # debt is immortal" path unless they also set an enforcement date.
        print(
            "  (No enforcement date set — legacy findings will not block "
            "until you regenerate the baseline or add --enforcement-date.)"
        )

    # Print counts by rule
    from collections import Counter
    by_rule = Counter(fp.rule_id for fp in fingerprints)
    if by_rule:
        print(f"\n  Findings by rule:")
        for rule_id, count in sorted(by_rule.items()):
            print(f"    {rule_id}: {count}")

    return 0


def _handle_baseline_compare(args) -> int:
    """Compare current findings against a baseline."""
    from .ratchet import (
        compare_findings,
        fingerprint_check_results,
        load_baseline,
    )
    from .review import run_review
    from .shell_policy import run_shell

    repo = Path(args.repo).expanduser().resolve()
    baseline_path = Path(args.baseline)

    if not baseline_path.exists():
        print(f"Baseline not found: {baseline_path}", file=sys.stderr)
        return 2

    baseline = load_baseline(baseline_path)

    # Get all tracked Python files
    try:
        result = subprocess.run(
            ["git", "ls-files", "*.py"],
            cwd=str(repo), capture_output=True, text=True, check=True,
        )
        files = [f.strip() for f in result.stdout.strip().splitlines() if f.strip()]
    except Exception:
        files = []

    print(f"Scanning {len(files)} files against baseline...")

    import tempfile
    from .evidence import CheckResult
    from .policy_manifest import (
        RULE_IDS,
        default_policy,
        get_check_severity,
        load_policy,
        should_run_check,
    )

    policy = default_policy()
    if args.policy:
        p = Path(args.policy)
        if p.exists():
            policy = load_policy(p)

    with tempfile.TemporaryDirectory() as tmpdir:
        review_result = run_review(
            repo, files, Path(tmpdir),
            run_shell_func=run_shell, timeout_s=30, strict=False,
        )

    check_results = []
    tools = review_result.get("tools", {})
    for check_name, tool_result in tools.items():
        if not should_run_check(policy, check_name):
            continue
        status = tool_result.get("status", "PASS")
        findings = tool_result.get("findings", [])
        if not isinstance(findings, list):
            findings = []
        severity = get_check_severity(policy, check_name)
        rule_id = RULE_IDS.get(check_name)

        normalized = []
        for f in findings:
            if isinstance(f, dict):
                normalized.append(f)
            elif isinstance(f, str):
                normalized.append({"message": f})

        cr = CheckResult(
            name=check_name,
            status="FAIL" if status == "FAIL" else "PASS",
            severity=severity,
            findings=normalized,
            files_checked=files,
            rule_id=rule_id,
        )
        check_results.append(cr)

    current_fps = fingerprint_check_results(check_results, repo)
    result = compare_findings(current_fps, baseline)

    print(f"Ratchet comparison: {result.disposition}")
    print(f"  Ratchet mode: {baseline.ratchet_mode}")
    print(f"  New findings: {len(result.new_findings)}")
    print(f"  Legacy findings: {len(result.legacy_findings)}")
    print(f"  Resolved findings: {len(result.resolved_findings)}")
    # I.3: surface the enforcement-date countdown (or days-since) so the
    # operator sees the deadline before/as it bites.  Advisory-only — does
    # not change disposition.
    if baseline.enforcement_date:
        from datetime import date as _date
        try:
            _ed = _date.fromisoformat(baseline.enforcement_date)
            _today = _date.today()
            _delta = (_ed - _today).days
            if _delta > 0:
                print(
                    f"  Enforcement date: {baseline.enforcement_date} "
                    f"({_delta} day(s) remaining — legacy findings will "
                    f"start failing after this date, regardless of ratchet_mode)"
                )
            elif _delta == 0:
                print(
                    f"  Enforcement date: {baseline.enforcement_date} "
                    f"(TODAY — legacy findings are now blocking)"
                )
            else:
                print(
                    f"  Enforcement date: {baseline.enforcement_date} "
                    f"(passed {-_delta} day(s) ago — legacy findings are now "
                    f"blocking per the deadline in this baseline)"
                )
        except ValueError:
            print(
                f"  Enforcement date: {baseline.enforcement_date} "
                f"(unparseable — treated as no deadline)"
            )
    for reason in result.reasons:
        print(f"  Reason: {reason}")

    return 0 if result.disposition != "FAIL" else 1


def _find_repo_root(start: Path) -> Path | None:
    for parent in [start] + list(start.parents):
        if (parent / ".git").exists():
            return parent
    return None


def main(argv=None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.command is None:
        parser.print_help()
        return 0

    if args.command == "version":
        print(__version__)
        # Also show update status on version command
        try:
            from .update_notifier import check_and_notify
            banner = check_and_notify(__version__)
            if banner:
                print(banner)
        except Exception:
            pass
        return 0

    if args.command == "status":
        from .status import format_status, gather_status
        repo = Path(args.repo).resolve()
        status_data = gather_status(repo)
        print(format_status(status_data))
        return 0

    # Non-blocking version update notification — fires on every command except
    # 'version' (which just printed the local version) and no-command help.
    # Reads from a local cache (~/.saturnday/version_cache.json) and never
    # blocks the main thread when a cache exists.
    try:
        from .update_notifier import check_and_notify as _check_update
        _update_banner = _check_update(__version__)
        if _update_banner:
            print(_update_banner, file=sys.stderr)
    except Exception:  # pragma: no cover — never break CLI startup
        pass

    # Attempt premium package discovery — non-fatal on absence or entitlement failure
    from saturnday.premium_registration import try_register_premium
    try_register_premium()

    if args.command == "scan":
        from .openclaw_scanner import scan_corpus, scan_skill

        def _scan_progress(msg: str) -> None:
            print(msg, file=sys.stderr)

        output_dir = Path(args.output).expanduser().resolve()

        # Load policy if specified
        policy = None
        if args.policy:
            from .policy_manifest import load_policy
            policy = load_policy(Path(args.policy).expanduser().resolve())

        if args.skill:
            skill_dir = Path(args.skill).expanduser().resolve()
            if not skill_dir.is_dir():
                print(f"Skill directory not found: {skill_dir}", file=sys.stderr)
                return 2
            output_dir.mkdir(parents=True, exist_ok=True)
            from .openclaw_scanner import write_single_skill_output

            result = scan_skill(
                skill_dir,
                policy=policy,
                include_syntax=True,
                strict=args.strict,
            )
            write_single_skill_output(output_dir, result, fmt=args.format)
            print(f"Skill: {skill_dir.name}")
            print(f"Disposition: {result.disposition}")
            print(f"Findings: {result.findings_count}")
            print(f"Output: {output_dir}")
            return 0 if result.disposition != "FAIL" else 1

        # Corpus scan
        corpus_root = Path(args.openclaw).expanduser().resolve()
        if not corpus_root.is_dir():
            print(f"Corpus root not found: {corpus_root}", file=sys.stderr)
            return 2

        summary = scan_corpus(
            corpus_root,
            output_dir,
            policy=policy,
            include_syntax=True,
            strict=args.strict,
            limit=args.limit,
            top_n=args.top_n,
            fmt=args.format,
            progress_callback=_scan_progress,
        )
        print(f"Corpus: {corpus_root}")
        print(f"Scanned: {summary.total_scanned} + {summary.total_scanned_degraded} degraded")
        print(f"Failed: {summary.total_failed}")
        print(f"Skipped: {summary.total_skipped}")
        print(f"Findings: {summary.total_findings}")
        print(f"Elapsed: {summary.elapsed_s:.1f}s")
        print(f"Output: {output_dir}")
        return 0

    if args.command == "governance":
        repo = Path(args.repo).expanduser().resolve()

        # Policy-schema refusal is surfaced here (option B fix): when
        # .saturnday-policy.yaml has exemption entries that don't match
        # the current schema, governance refuses rather than running
        # with a misleading partial exemption set.
        from ._exceptions import PolicySchemaError as _PolicySchemaError
        try:
            if getattr(args, "full", False):
                # Full repo review — scan all tracked files
                from .governance import run_full_repo_review
                policy_path = None
                if args.policy:
                    p = Path(args.policy)
                    if p.exists():
                        policy_path = p
                elif (repo / ".saturnday-policy.yaml").is_file():
                    policy_path = repo / ".saturnday-policy.yaml"
                pack, evidence_path = run_full_repo_review(
                    repo, policy_path=policy_path,
                )
            else:
                # Diff-based check
                from .governance import run_governance_check
                policy_path = None
                if args.policy:
                    p = Path(args.policy)
                    if p.exists():
                        policy_path = p

                pack, evidence_path = run_governance_check(
                    repo_path=repo,
                    diff_range=args.diff,
                    staged=args.staged,
                    policy_path=policy_path,
                    output_dir=Path(args.output) if args.output else None,
                    strict=args.strict,
                )
        except _PolicySchemaError as _psc_exc:
            print("", file=sys.stderr)
            print(str(_psc_exc), file=sys.stderr)
            print("", file=sys.stderr)
            return 1

        # Security triage: LLM-based false positive filtering (opt-in)
        if getattr(args, "triage", False):
            try:
                _triage = capability_registry.get("security_triage")
                if _triage is not None:
                    from ._types import CoderConfig
                    from .coder_adapter import CLI_BACKENDS
                    _triage_backend = getattr(args, "triage_backend", "claude-cli")
                    if _triage_backend in CLI_BACKENDS:
                        _triage_config = CoderConfig(backend=_triage_backend)
                    else:
                        import os as _os_triage
                        _triage_key = _os_triage.environ.get(
                            "ANTHROPIC_API_KEY" if _triage_backend == "anthropic" else "OPENAI_API_KEY", ""
                        )
                        if not _triage_key:
                            print("\nSecurity triage: skipped (no API key set for {})".format(_triage_backend), file=sys.stderr)
                            _triage_config = None
                        else:
                            _triage_config = CoderConfig(backend=_triage_backend, api_key=_triage_key)
                    if _triage_config:
                        _all_findings: list[dict] = []
                        for _cr in pack.check_results:
                            _all_findings.extend(_cr.findings)
                        _triaged = _triage.filter_findings(_all_findings, repo, _triage_config)
                        _removed = len(_all_findings) - len(_triaged)
                        if _removed > 0:
                            print(f"\nSecurity triage: filtered {_removed} false positive(s)")
                            _triaged_set = set(id(f) for f in _triaged)
                            for _cr in pack.check_results:
                                _cr.findings = [f for f in _cr.findings if id(f) in _triaged_set]
                                _cr.status = "FAIL" if _cr.findings else "PASS"
                            from .evidence import compute_disposition
                            pack.disposition, pack.disposition_reasons = compute_disposition(pack.check_results)
            except Exception as _triage_err:
                logger.debug("Security triage failed: %s", _triage_err)

        if not pack.check_results:
            diff_desc = args.diff or "HEAD~1..HEAD"
            print(
                f"\nNo changed files found in diff range '{diff_desc}'.\n"
                f"No checks were executed.\n\n"
                f"To scan a wider range:\n"
                f"  saturnday check --repo {args.repo} --diff $(git rev-list --max-parents=0 HEAD)..HEAD\n\n"
                f"To scan staged changes:\n"
                f"  saturnday governance --repo {args.repo} --staged\n",
                file=sys.stderr,
            )
        print(f"Disposition: {pack.disposition}")
        print(f"Checks run: {len(pack.check_results)}")
        # Show findings by category so Claude (and the user) can see what's wrong
        by_check: dict[str, int] = {}
        for cr in pack.check_results:
            if cr.findings:
                by_check[cr.name] = len(cr.findings)
        if by_check:
            print("\nFindings:")
            for name, count in sorted(by_check.items(), key=lambda x: -x[1]):
                print(f"  {name}: {count}")
        total = sum(len(cr.findings) for cr in pack.check_results)
        print(f"\nTotal findings: {total}")
        # Fix A: governance is observational — we do not silently bootstrap
        # a baseline here — but when an operator sees a FAIL disposition on
        # a repo that has no baseline, tell them exactly how to capture the
        # existing findings as known debt so future commits aren't blocked.
        baseline_path = repo / ".saturnday-baseline.json"
        if pack.disposition == "FAIL" and total > 0 and not baseline_path.is_file():
            print(
                "\nNOTE: no .saturnday-baseline.json found in this repo.  "
                "The current findings include both pre-existing debt and any "
                "regressions you may have introduced — governance cannot tell "
                "them apart without a baseline.\n"
                "To capture the current state as known debt so future commits "
                "and runs only block on NEW regressions, run:\n"
                "  saturnday hook install\n"
                "  (which seeds .saturnday-baseline.json and installs the "
                "pre-commit hook in one step)"
            )
        # Flag environment findings specifically
        env_count = sum(
            len(cr.findings) for cr in pack.check_results
            if cr.name in ("import_check", "api_version_check")
            and any(f.get("kind") == "declared_not_installed" for f in cr.findings)
        )
        if env_count:
            print(f"\n{env_count} finding(s) are about packages declared but not installed.")
            print("Install missing packages to resolve these.")
        print(f"\nEvidence: {evidence_path}")

        # Generate detailed scan report
        try:
            from .reporting import generate_scan_report
            report_path = generate_scan_report(pack, evidence_path, repo)
            print(f"Report: {report_path}")
        except Exception as exc:
            logger.warning("Failed to generate scan report: %s", exc)

        return 0 if pack.disposition != "FAIL" else 1

    if args.command == "hook":
        return _handle_hook(args)

    if args.command == "public-fix":
        if args.dry_run and args.apply:
            print("Error: --dry-run and --apply cannot be used together.", file=sys.stderr)
            return 2
        from .public_fix import (
            format_apply_summary,
            format_dry_run,
            run_public_fix_apply,
            run_public_fix_dry_run,
        )
        repo = Path(args.repo).resolve()
        if args.apply:
            summary = run_public_fix_apply(repo)
            print(format_apply_summary(summary))
        else:
            # Default to dry-run
            plan = run_public_fix_dry_run(repo)
            print(format_dry_run(plan))
        return 0

    if args.command == "public-check":
        from .public_check import format_public_check, run_public_check
        repo = Path(args.repo).resolve()
        result = run_public_check(repo, commit_range=args.commits)
        print(format_public_check(result))
        if result.verdict == "NOT_READY":
            return 1
        return 0

    if args.command == "evidence":
        if getattr(args, "evidence_action", None) == "list":
            from .evidence_list import format_evidence_list, gather_evidence
            repo = Path(getattr(args, "repo", ".")).resolve()
            print(format_evidence_list(gather_evidence(repo)))
            return 0
        print("Usage: saturnday evidence list [--repo .]", file=sys.stderr)
        return 2

    if args.command == "policy":
        if getattr(args, "policy_action", None) == "show":
            from .policy_show import format_policy, gather_policy
            repo = Path(getattr(args, "repo", ".")).resolve()
            print(format_policy(gather_policy(repo)))
            return 0
        if getattr(args, "policy_action", None) == "validate":
            repo = Path(getattr(args, "repo", ".")).resolve()
            return _validate_policy(repo)
        print("Usage: saturnday policy {show,validate} [--repo .]", file=sys.stderr)
        return 2

    if args.command == "init-gitignore":
        return _handle_init_gitignore(args)

    if args.command == "baseline":
        if args.baseline_action == "generate":
            return _handle_baseline_generate(args)
        elif args.baseline_action == "compare":
            return _handle_baseline_compare(args)
        else:
            print("Usage: saturnday baseline {generate|compare}", file=sys.stderr)
            return 2

    if args.command == "check":
        from .governance import run_governance_check

        auto_install = getattr(args, "auto_install_deps", False)
        if auto_install and sys.stdin.isatty():
            # Interactive mode: show what we'll install and ask permission
            from .review import _get_installable_dependencies
            repo = Path(args.repo).expanduser().resolve()
            deps = _get_installable_dependencies(repo)
            if deps:
                print(f"Saturnday will install {len(deps)} package(s) in a temporary venv:")
                for d in deps[:10]:
                    print(f"  - {d}")
                if len(deps) > 10:
                    print(f"  ... and {len(deps) - 10} more")
                try:
                    answer = input("Proceed? [y/N] ").strip().lower()
                except (EOFError, KeyboardInterrupt):
                    answer = ""
                if answer not in ("y", "yes"):
                    print("Skipping auto-install — API checks will use local packages only.")
                    auto_install = False

        # Resolve policy path — skip if file doesn't exist
        policy_path = None
        if args.policy:
            p = Path(args.policy)
            if p.exists():
                policy_path = p
            else:
                print(f"Policy file not found, using defaults: {args.policy}", file=sys.stderr)

        pack, evidence_path = run_governance_check(
            repo_path=Path(args.repo).expanduser().resolve(),
            diff_range=args.diff,
            staged=args.staged,
            policy_path=policy_path,
            output_dir=Path(args.output) if args.output else None,
            strict=args.strict,
            auto_install_deps=auto_install,
        )
        print(f"\nEvidence dir: {evidence_path}")
        print(f"Disposition:  {pack.disposition}")

        if not pack.check_results:
            diff_desc = args.diff or "HEAD~1..HEAD"
            print(
                f"\nNo changed files found in diff range '{diff_desc}'.\n"
                f"No checks were executed.\n\n"
                f"To scan a wider range:\n"
                f"  saturnday check --repo {args.repo} --diff $(git rev-list --max-parents=0 HEAD)..HEAD\n\n"
                f"To scan staged changes:\n"
                f"  saturnday governance --repo {args.repo} --staged\n",
                file=sys.stderr,
            )

        # Print findings summary to terminal
        if pack.check_results:
            print(f"\n{'Check':<25} {'Status':<8} {'Severity':<10} {'Findings'}")
            print("-" * 65)
            for cr in pack.check_results:
                count = len(cr.findings)
                marker = ""
                if cr.status == "FAIL":
                    marker = " <<"
                print(f"{cr.name:<25} {cr.status:<8} {cr.severity:<10} {count}{marker}")

            # Print actual findings for failed checks
            failed = [cr for cr in pack.check_results if cr.status == "FAIL"]
            if failed:
                print(f"\n{'=' * 65}")
                print("FINDINGS")
                print(f"{'=' * 65}")
                for cr in failed:
                    print(f"\n[{cr.severity.upper()}] {cr.name} — {len(cr.findings)} finding(s)")
                    for i, f in enumerate(cr.findings, 1):
                        file = f.get("file") or f.get("filename") or ""
                        line = f.get("line") or f.get("line_number") or ""
                        loc = f"{file}:{line}" if file else ""
                        detail = (
                            f.get("detail")
                            or f.get("issue_text")
                            or f.get("message")
                            or f.get("pattern", "")
                        )
                        kind = f.get("kind", "")
                        kind_str = f" [{kind}]" if kind else ""
                        if loc:
                            print(f"  {i}. {loc}{kind_str}: {detail}")
                        else:
                            print(f"  {i}.{kind_str} {detail}")

        print()
        return 0 if pack.disposition != "FAIL" else 1

    if args.command == "release-preflight":
        return _cmd_release_preflight(args)

    if args.command == "release-approve":
        action = getattr(args, "release_approve_action", None)

        if action == "list":
            from .release_signoff_list import format_signoff_list, load_signoff_records
            evidence_path = Path(args.evidence).resolve()
            if not evidence_path.is_dir():
                print(f"Error: evidence directory not found: {evidence_path}", file=sys.stderr)
                return 1
            records = load_signoff_records(evidence_path)
            print(format_signoff_list(records))
            return 0

        if action == "check":
            from .release_signoff_list import check_signoff_completeness
            evidence_path = Path(args.evidence).resolve()
            if not evidence_path.is_dir():
                print(f"Error: evidence directory not found: {evidence_path}", file=sys.stderr)
                return 1
            minimum = getattr(args, "minimum", 2)
            satisfied, reason = check_signoff_completeness(evidence_path, minimum)
            print(f"  {reason}")
            return 0 if satisfied else 1

        # Recording path — validate required args
        if not args.evidence or not args.approver:
            print("Usage: saturnday release-approve --evidence DIR --approver NAME", file=sys.stderr)
            print("  Or:  saturnday release-approve list --evidence DIR", file=sys.stderr)
            print("  Or:  saturnday release-approve check --evidence DIR", file=sys.stderr)
            return 2

        _handler = capability_registry.get("release_governance")
        if _handler is None:
            print(
                "Release approval workflow requires saturnday-premium.",
                file=sys.stderr,
            )
            return 1
        try:
            return _handler.approve(args)
        except Exception as exc:
            print(f"Error: {exc}", file=sys.stderr)
            return 1

    if args.command == "release-exception":
        action = getattr(args, "release_exception_action", None)

        if action == "list":
            from .release_exception_list import format_exception_list, load_exception_records
            evidence_path = Path(args.evidence).resolve()
            if not evidence_path.is_dir():
                print(f"Error: evidence directory not found: {evidence_path}", file=sys.stderr)
                return 1
            records = load_exception_records(evidence_path)
            print(format_exception_list(records))
            return 0

        # Recording path — validate required args
        if not args.evidence or not args.rule or not args.reason or not args.approver:
            print("Usage: saturnday release-exception --evidence DIR --rule RULE --reason REASON --approver NAME", file=sys.stderr)
            print("  Or:  saturnday release-exception list --evidence DIR", file=sys.stderr)
            return 2

        _handler = capability_registry.get("release_governance")
        if _handler is None:
            print("Release exception workflow is not enabled in this environment. Entitlement required.", file=sys.stderr)
            return 1
        try:
            return _handler.record_exception(vars(args), Path(args.evidence))
        except Exception as exc:
            print(f"Error: {exc}", file=sys.stderr)
            return 1

    # --- Run / Repair / Interactive / Document subcommands ---
    _run_cmd_map = {
        "run": _cmd_run,
        "resume": _cmd_resume,
        "rerun-failed": _cmd_rerun_failed,
        "rerun-remaining": _cmd_rerun_remaining,
        "validate-plan": _cmd_validate_plan,
        "explain-failure": _cmd_explain_failure,
        "plan": _cmd_plan,
        "plan-confirm": _cmd_plan_confirm,
        "publish-preflight": _cmd_publish_preflight,
        "repair": _cmd_repair,
        "start": _cmd_start,
        "approve": _cmd_approve,
    }
    handler = _run_cmd_map.get(args.command)
    if handler is not None:
        return handler(args)

    parser.print_help()
    return 0


