from __future__ import annotations

import argparse
import json
import logging
import os
import subprocess
import sys
from pathlib import Path
from importlib import metadata
from urllib.parse import urlparse, unquote

from .version import __version__
from saturnday import capability_registry

logger = logging.getLogger(__name__)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="saturnday",
        description="AI-specific governance checks for code generated by Claude, Cursor, Copilot, and other AI tools",
    )
    subparsers = parser.add_subparsers(dest="command")

    subparsers.add_parser("version", help="Print version and exit")

    # --- Status: repo governance introspection ---
    status_parser = subparsers.add_parser("status", help="Show current governance state of a repository (read-only)")
    status_parser.add_argument("--repo", default=".", help="Path to git repo (default: .)")
    status_parser.add_argument("--verbose", "-v", action="store_true")

    check_parser = subparsers.add_parser("check", help="Run governance checks on a diff")
    check_parser.add_argument("--repo", required=True, help="Path to git repo")
    check_parser.add_argument("--diff", default="HEAD~1..HEAD", help="Git diff range (default: HEAD~1..HEAD, which checks only the last commit)")
    check_parser.add_argument("--staged", action="store_true", help="Check staged changes")
    check_parser.add_argument("--policy", help="Path to saturnday-policy.yaml")
    check_parser.add_argument("--output", help="Output dir for evidence pack")
    check_parser.add_argument("--strict", action="store_true", help="Strict mode")
    check_parser.add_argument(
        "--auto-install-deps", action="store_true",
        help="Install project deps in a temp venv to verify API usage (prompts for confirmation)",
    )

    scan_parser = subparsers.add_parser("scan", help="Scan OpenClaw skill repos for governance issues")
    scan_group = scan_parser.add_mutually_exclusive_group(required=True)
    scan_group.add_argument("--openclaw", help="Path to OpenClaw skills corpus root")
    scan_group.add_argument("--skill", help="Path to a single skill directory")
    scan_parser.add_argument("--output", required=True, help="Output directory for scan results")
    scan_parser.add_argument("--format", choices=["json", "markdown", "both"], default="both",
                             help="Output format: json, markdown, or both (default: both)")
    scan_parser.add_argument("--limit", type=int, help="Limit number of skills to scan")
    scan_parser.add_argument("--top-n", type=int, help="Include detailed findings for top N worst skills")
    scan_parser.add_argument("--strict", action="store_true",
                             help="Fail if required runtimes (Node) unavailable")
    scan_parser.add_argument("--policy", help="Path to policy YAML (default: built-in OpenClaw preset)")

    # Governance command — run governance checks (alias for check with sensible defaults)
    gov_parser = subparsers.add_parser("governance", help="Run governance checks on a repository")
    gov_parser.add_argument("--repo", default=".", help="Path to git repo (default: .)")
    gov_parser.add_argument("--diff", default="HEAD~1..HEAD", help="Git diff range (default: HEAD~1..HEAD, which checks only the last commit)")
    gov_parser.add_argument("--staged", action="store_true", help="Check staged changes")
    gov_parser.add_argument("--full", action="store_true", help="Review all tracked files (not just a diff)")
    gov_parser.add_argument("--policy", help="Path to saturnday-policy.yaml")
    gov_parser.add_argument("--output", help="Output dir for evidence pack")
    gov_parser.add_argument("--strict", action="store_true", default=True,
                            help="Strict mode (default: true for governance)")
    gov_parser.add_argument("--triage", action="store_true",
                            help="Run LLM-based security triage to filter false positives")
    gov_parser.add_argument("--triage-backend", default="claude-cli",
                            choices=["claude-cli", "codex-cli", "openclaude", "anthropic", "openai"],
                            help="Backend for security triage LLM calls (default: claude-cli)")
    # Document mode flag (additive — shows document findings in addition to code findings)
    gov_parser.add_argument(
        "--document", action="store_true", default=False,
        help="Include document governance findings when --full is set.",
    )

    # --- Document: approve subcommand ---
    approve_parser = subparsers.add_parser(
        "approve",
        help="Document approval workflow — record, list, or check sign-off status (entitlement required for recording)",
    )
    approve_sub = approve_parser.add_subparsers(dest="approve_action")

    # approve list
    approve_list_sub = approve_sub.add_parser("list", help="List all approval records (read-only)")
    approve_list_sub.add_argument("--repo", default=".", help="Path to git repo (default: .)")
    approve_list_sub.add_argument("--verbose", "-v", action="store_true")

    # approve check
    approve_check_sub = approve_sub.add_parser("check", help="Check sign-off completeness for a document")
    approve_check_sub.add_argument("--document", required=True, metavar="DOC_ID", help="Document run ID to check")
    approve_check_sub.add_argument("--repo", default=".", help="Path to git repo (default: .)")
    approve_check_sub.add_argument("--verbose", "-v", action="store_true")

    # approve (record) — direct flags on the approve parser for backward compat
    approve_parser.add_argument(
        "--document", metavar="RUN_ID",
        help="Document run ID to approve (matches the document_id in the run plan).",
    )
    approve_parser.add_argument(
        "--role",
        help="Sign-off role being satisfied (e.g. cfo, legal, eng-lead).",
    )
    approve_parser.add_argument(
        "--actor",
        help="Name of the person or system recording this approval.",
    )
    approve_parser.add_argument(
        "--status", default="approved",
        choices=["approved", "rejected", "pending"],
        help="Approval status (default: approved).",
    )
    approve_parser.add_argument("--notes", default="", help="Optional reviewer comment.")
    approve_parser.add_argument(
        "--repo", default=".",
        help="Path to the repo containing the approvals file (default: .).",
    )
    approve_parser.add_argument("--verbose", "-v", action="store_true")

    # Baseline command — generate or compare baselines
    baseline_parser = subparsers.add_parser("baseline", help="Generate or compare ratchet baselines")
    baseline_sub = baseline_parser.add_subparsers(dest="baseline_action")

    gen_parser = baseline_sub.add_parser("generate", help="Generate a baseline snapshot")
    gen_parser.add_argument("--repo", required=True, help="Path to git repo")
    gen_parser.add_argument("--output", default=".saturnday-baseline.json",
                            help="Output path for baseline JSON")
    gen_parser.add_argument(
        "--enforcement-date", default="",
        help=(
            "ISO date (YYYY-MM-DD).  HARD DEADLINE to clear legacy debt.  "
            "Before this date, the baseline's ratchet behaves as named.  "
            "Once the date has passed, BOTH 'block_new' and 'ratchet_down' "
            "additionally fail on any remaining pre-existing (legacy) finding.  "
            "Leave empty to allow legacy debt forever."
        ),
    )
    gen_parser.add_argument(
        "--ratchet-mode", default="block_new",
        choices=["block_new", "ratchet_down"],
        help=(
            "Ratchet behaviour BEFORE --enforcement-date (if any).  "
            "'block_new' (default): only newly introduced findings fail; "
            "legacy debt is frozen and allowed.  "
            "'ratchet_down': newly introduced findings fail AND the total "
            "non-waived finding count must not exceed the baseline — prevents "
            "resolve-and-replace churn.  "
            "Note: --enforcement-date, when set and in the past, makes BOTH "
            "modes additionally fail on legacy findings — the deadline is "
            "what switches on post-deadline strictness, not the mode name."
        ),
    )
    gen_parser.add_argument("--policy", help="Path to saturnday-policy.yaml")

    cmp_parser = baseline_sub.add_parser("compare", help="Compare current findings against baseline")
    cmp_parser.add_argument("--repo", required=True, help="Path to git repo")
    cmp_parser.add_argument("--baseline", default=".saturnday-baseline.json",
                            help="Path to baseline JSON")
    cmp_parser.add_argument("--policy", help="Path to saturnday-policy.yaml")

    # --- Run: execute a project plan ---
    run_parser = subparsers.add_parser("run", help="Execute a project plan")
    run_parser.add_argument("--plan", required=True, help="Path to the project plan JSON file")
    run_parser.add_argument("--repo", required=True, help="Path to the target repository")
    run_parser.add_argument(
        "--backend", required=True,
        choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"],
        help="Coder backend to use",
    )
    run_parser.add_argument(
        "--standards-dir", default="./senior_engineering_standards",
        help="Path to engineering standards directory (default: ./senior_engineering_standards)",
    )
    run_parser.add_argument("--output-dir", default=None, help="Evidence output directory")
    run_parser.add_argument("--api-key", default=None, help="API key (for openai/anthropic backends)")
    run_parser.add_argument("--base-url", default=None, help="API base URL override")
    run_parser.add_argument("--model", default=None, help="Model name override")
    run_parser.add_argument("--temperature", type=float, default=0.0, help="Sampling temperature (default: 0.0)")
    run_parser.add_argument("--timeout", type=int, default=1200, help="Request timeout in seconds (default: 1200)")
    run_parser.add_argument("--max-tokens", type=int, default=16384, help="Max tokens in coder response (default: 16384)")
    run_parser.add_argument("--verbose", "-v", action="store_true", help="Enable verbose (DEBUG) logging")
    run_parser.add_argument(
        "--strict-dod", action="store_true", default=False,
        help="Exit with code 1 if the definition of done is not met after the run completes",
    )
    run_parser.add_argument(
        "--auto-repair", action="store_true", default=False,
        help=(
            "After all retries for a ticket are exhausted, attempt one automatic "
            "repair pass using the repair subsystem.  If the repair fixes the "
            "governance finding and re-governance passes, the ticket is committed "
            "as PASS.  Has no effect if the ticket passes on a normal attempt."
        ),
    )
    run_parser.add_argument(
        "--lessons", default=None, metavar="DB_PATH",
        help=(
            "Path to the SQLite lessons database.  When provided, failure lessons "
            "from past runs are injected into the coder prompt before each ticket, "
            "and new lessons are recorded when a ticket exhausts all retries.  "
            "Defaults to off.  Suggested path: ~/.saturnday/lessons.db"
        ),
    )
    run_parser.add_argument(
        "--no-role-passes", action="store_true", default=False,
        help="Disable post-run role passes",
    )
    run_parser.add_argument(
        "--approve-acceptance-setup", action="store_true", default=False,
        help=(
            "Non-interactive approval for plans that declare acceptance_setup "
            "steps.  Equivalent to typing 'y' at the interactive prompt — "
            "the setup steps run, then the proof runs.  Without this flag "
            "(and without SATURNDAY_APPROVE_SETUP=1), non-TTY runs skip the "
            "acceptance phase and mark DoD NOT MET.  TTY runs are unaffected."
        ),
    )
    run_parser.add_argument(
        "--work-branch", nargs="?",
        const="__saturnday_auto__",
        default=None,
        metavar="NAME",
        help=(
            "I.4: opt-in work-branch isolation.  When passed without a "
            "value, Saturnday creates a branch named "
            "'saturnday/run-<UTC>' from the current HEAD before any "
            "governed commit lands, and keeps the operator on that "
            "branch at the end.  When passed with an explicit NAME, "
            "uses that name instead.  Refuses if the working tree is "
            "dirty, HEAD is detached, or the requested branch already "
            "exists.  Has no effect when not passed — existing "
            "behaviour is preserved."
        ),
    )
    # δ: targeted proof-question pre-answer.  Repeatable.
    # Format: --proof-answer kind=answer  (e.g. --proof-answer cli_entrypoint='python -m mypkg run --in data.csv')
    # When Phase 4 / Phase 5 proof derivation fails and the run is
    # non-interactive, the matching pre-answer closes the gap; without
    # it the run ends with an explicit refusal narrative instead of a
    # silent DoD NOT MET.
    run_parser.add_argument(
        "--proof-answer", action="append", default=None, metavar="KIND=ANSWER",
        help=(
            "δ: pre-answer a targeted proof question for non-interactive "
            "runs.  Kinds: cli_entrypoint, ws_endpoint, library_call, "
            "worker_cycle, frontend_path, custom_proof.  Repeatable."
        ),
    )
    run_parser.add_argument(
        "--max-failures", type=int, default=None, metavar="N",
        help=(
            "Override the consecutive-failure stop threshold (default: 3). "
            "After N consecutive ticket failures the run bails to avoid "
            "burning more coder calls on a broken state.  Raise this on "
            "long or noisy plans; lower it for tight API-budget runs."
        ),
    )

    # --- Run: resume from checkpoint ---
    resume_parser = subparsers.add_parser("resume", help="Continue a run from ledger checkpoint (re-runs FAIL + SKIP + PENDING, skips PASS + CODED_UNGOVERNED)")
    resume_parser.add_argument("--plan", required=True, help="Path to the project plan JSON file")
    resume_parser.add_argument("--repo", required=True, help="Path to the target repository")
    resume_parser.add_argument("--backend", required=True, choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"])
    resume_parser.add_argument("--output-dir", required=True, help="Evidence directory from the prior run")
    resume_parser.add_argument("--standards-dir", default="./senior_engineering_standards")
    resume_parser.add_argument("--api-key", default=None)
    resume_parser.add_argument("--base-url", default=None)
    resume_parser.add_argument("--model", default=None)
    resume_parser.add_argument("--temperature", type=float, default=0.0)
    resume_parser.add_argument("--timeout", type=int, default=1200)
    resume_parser.add_argument("--max-tokens", type=int, default=16384)
    resume_parser.add_argument("--verbose", "-v", action="store_true")
    resume_parser.add_argument(
        "--approve-acceptance-setup", action="store_true", default=False,
        help="α: approve acceptance_setup steps non-interactively (same as on 'run').",
    )
    resume_parser.add_argument(
        "--work-branch", nargs="?",
        const="__saturnday_auto__",
        default=None,
        metavar="NAME",
        help=(
            "I.4: continue on the work branch recorded by the prior run.  "
            "Pass an explicit NAME to override.  See 'saturnday run --help' "
            "for full semantics."
        ),
    )
    resume_parser.add_argument(
        "--proof-answer", action="append", default=None, metavar="KIND=ANSWER",
        help="δ: pre-answer a targeted proof question (see 'saturnday run --help').",
    )
    resume_parser.add_argument(
        "--max-failures", type=int, default=None, metavar="N",
        help="Override consecutive-failure stop threshold (see 'saturnday run --help').",
    )

    # --- Run: rerun failed tickets ---
    rerun_parser = subparsers.add_parser("rerun-failed", help="Re-execute only failed tickets (FAIL + CODED_UNGOVERNED)")
    rerun_parser.add_argument("--plan", required=True, help="Path to the project plan JSON file")
    rerun_parser.add_argument("--repo", required=True, help="Path to the target repository")
    rerun_parser.add_argument("--backend", required=True, choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"])
    rerun_parser.add_argument("--output-dir", required=True, help="Evidence directory from the prior run")
    rerun_parser.add_argument("--standards-dir", default="./senior_engineering_standards")
    rerun_parser.add_argument("--api-key", default=None)
    rerun_parser.add_argument("--base-url", default=None)
    rerun_parser.add_argument("--model", default=None)
    rerun_parser.add_argument("--temperature", type=float, default=0.0)
    rerun_parser.add_argument("--timeout", type=int, default=1200)
    rerun_parser.add_argument("--max-tokens", type=int, default=16384)
    rerun_parser.add_argument("--verbose", "-v", action="store_true")
    rerun_parser.add_argument(
        "--approve-acceptance-setup", action="store_true", default=False,
        help="α: approve acceptance_setup steps non-interactively (same as on 'run').",
    )
    rerun_parser.add_argument(
        "--work-branch", nargs="?",
        const="__saturnday_auto__",
        default=None,
        metavar="NAME",
        help="I.4: continue on the recorded work branch or override with NAME.",
    )
    rerun_parser.add_argument(
        "--proof-answer", action="append", default=None, metavar="KIND=ANSWER",
        help="δ: pre-answer a targeted proof question (see 'saturnday run --help').",
    )
    rerun_parser.add_argument(
        "--max-failures", type=int, default=None, metavar="N",
        help="Override consecutive-failure stop threshold (see 'saturnday run --help').",
    )

    # --- Run: rerun remaining unattempted tickets ---
    rerun_remaining_parser = subparsers.add_parser("rerun-remaining", help="Re-execute only skipped/unattempted tickets (SKIP + PENDING)")
    rerun_remaining_parser.add_argument("--plan", required=True, help="Path to the project plan JSON file")
    rerun_remaining_parser.add_argument("--repo", required=True, help="Path to the target repository")
    rerun_remaining_parser.add_argument("--backend", required=True, choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"])
    rerun_remaining_parser.add_argument("--output-dir", required=True, help="Evidence directory from the prior run")
    rerun_remaining_parser.add_argument("--standards-dir", default="./senior_engineering_standards")
    rerun_remaining_parser.add_argument("--api-key", default=None)
    rerun_remaining_parser.add_argument("--base-url", default=None)
    rerun_remaining_parser.add_argument("--model", default=None)
    rerun_remaining_parser.add_argument("--temperature", type=float, default=0.0)
    rerun_remaining_parser.add_argument("--timeout", type=int, default=1200)
    rerun_remaining_parser.add_argument("--max-tokens", type=int, default=16384)
    rerun_remaining_parser.add_argument("--verbose", "-v", action="store_true")
    rerun_remaining_parser.add_argument(
        "--approve-acceptance-setup", action="store_true", default=False,
        help="α: approve acceptance_setup steps non-interactively (same as on 'run').",
    )
    rerun_remaining_parser.add_argument(
        "--work-branch", nargs="?",
        const="__saturnday_auto__",
        default=None,
        metavar="NAME",
        help="I.4: continue on the recorded work branch or override with NAME.",
    )
    rerun_remaining_parser.add_argument(
        "--proof-answer", action="append", default=None, metavar="KIND=ANSWER",
        help="δ: pre-answer a targeted proof question (see 'saturnday run --help').",
    )
    rerun_remaining_parser.add_argument(
        "--max-failures", type=int, default=None, metavar="N",
        help="Override consecutive-failure stop threshold (see 'saturnday run --help').",
    )

    # --- Run: validate-plan ---
    validate_parser = subparsers.add_parser("validate-plan", help="Validate a plan and print errors")
    validate_parser.add_argument("--plan", required=True, help="Path to the project plan JSON file")
    validate_parser.add_argument(
        "--repo", default=".",
        help="Repository root used to resolve verify_cmd tools against declared dependencies.",
    )
    validate_parser.add_argument("--verbose", "-v", action="store_true")

    # --- Run: explain-failure ---
    explain_parser = subparsers.add_parser("explain-failure", help="Print remediation report for a failed run")
    explain_parser.add_argument("--output-dir", required=True, help="Evidence directory from the run")
    explain_parser.add_argument("--verbose", "-v", action="store_true")

    # --- Run: plan generation ---
    plan_parser = subparsers.add_parser("plan", help="Generate a plan from a project brief")
    plan_parser.add_argument("--brief", required=False, default=None, help="Plain-language project brief")
    plan_parser.add_argument("--repo", required=True, help="Path to the target repository")
    plan_parser.add_argument("--backend", required=True, choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"])
    plan_parser.add_argument("--planner-backend", default=None, choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"])
    plan_parser.add_argument("--output", default=None, help="Path for plan.json output")
    plan_parser.add_argument(
        "--commit", action="store_true", default=False,
        help="Commit the generated plan to git (uses normal verified commit)",
    )
    # Fix 75: clarification answers for ambiguous briefs.  Repeatable.
    # Format: --clarify trigger_kind=answer  (e.g. --clarify mode_ambiguous=cli_tool)
    # In non-interactive mode, every blocking trigger MUST be answered via
    # this flag or planning is refused.
    plan_parser.add_argument(
        "--clarify", action="append", default=None, metavar="KIND=ANSWER",
        help=(
            "Fix 75: answer a clarification trigger.  Format: "
            "--clarify mode_ambiguous=cli_tool.  Repeatable.  In "
            "non-interactive mode, all blocking triggers must be answered."
        ),
    )
    plan_parser.add_argument("--api-key", default=None)
    plan_parser.add_argument("--base-url", default=None)
    plan_parser.add_argument("--model", default=None)
    plan_parser.add_argument("--planner-model", default=None, help="Model override for planner backend")
    plan_parser.add_argument("--temperature", type=float, default=0.0)
    plan_parser.add_argument("--timeout", type=int, default=1200)
    plan_parser.add_argument("--max-tokens", type=int, default=16384)
    plan_parser.add_argument("--verbose", "-v", action="store_true")
    # Document mode: generate a document plan from a doc-spec.yaml
    plan_parser.add_argument(
        "--doc-spec", default=None, metavar="DOC_SPEC",
        help="Path to doc-spec.yaml.  When provided, generate a document plan instead of a code plan.",
    )

    # --- plan-confirm: generate plan + interactive DoD approval gate ---
    pc_parser = subparsers.add_parser(
        "plan-confirm",
        help="Generate a plan and present the DoD approval gate (use instead of plan for new projects)",
    )
    pc_parser.add_argument("--brief", required=True, help="Plain-language project brief")
    pc_parser.add_argument("--repo", required=True, help="Path to the target repository")
    pc_parser.add_argument(
        "--backend", required=True,
        choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"],
    )
    pc_parser.add_argument("--output", default=None, help="Path for plan.json output")
    pc_parser.add_argument("--verbose", "-v", action="store_true")
    # Fix 75: same --clarify flag here so plan-confirm can run non-interactively.
    pc_parser.add_argument(
        "--clarify", action="append", default=None, metavar="KIND=ANSWER",
        help="Fix 75: clarification answer (see saturnday plan --help).",
    )

    # --- Interactive front door ---
    start_parser = subparsers.add_parser("start", help="Interactive guided workflow")
    start_parser.add_argument(
        "--repo", default=".",
        help="Path to the repo or skill directory (default: .)",
    )
    # Document mode flags (additive — do not affect code mode when absent)
    start_parser.add_argument(
        "--document", action="store_true", default=False,
        help="Run in document mode instead of code mode.",
    )
    start_parser.add_argument(
        "--doc-spec", default=None, metavar="DOC_SPEC",
        help="Path to doc-spec.yaml (required when --document is set).",
    )
    # Backend args for document mode (ignored in code mode).
    start_parser.add_argument(
        "--backend", default=None,
        choices=["codex-cli", "claude-cli", "openclaude", "openai", "anthropic"],
        help="Coder backend for document mode (default: claude-cli).",
    )
    start_parser.add_argument("--api-key", default=None, help="API key for API backends")
    start_parser.add_argument("--base-url", default=None, help="API base URL")
    start_parser.add_argument("--model", default=None, help="Model identifier")
    start_parser.add_argument("--temperature", type=float, default=0.0)
    start_parser.add_argument("--max-tokens", type=int, default=16384)
    start_parser.add_argument("--timeout", type=int, default=1200)
    start_parser.add_argument("--verbose", "-v", action="store_true")
    start_parser.add_argument("--output-dir", default=None, help="Evidence output directory (document mode)")
    start_parser.add_argument(
        "--work-branch", nargs="?",
        const="__saturnday_auto__",
        default=None,
        metavar="NAME",
        help=(
            "I.4: forward an opt-in work branch into the guided run / "
            "repair flow.  See 'saturnday run --help' for full semantics."
        ),
    )

    # --- Guard: publish-preflight ---
    preflight_parser = subparsers.add_parser("publish-preflight", help="Check if a skill is ready to publish")
    preflight_parser.add_argument("--skill", required=True, help="Path to the skill directory")
    preflight_parser.add_argument("--verbose", "-v", action="store_true")

    # --- Guard: repair ---
