def _require_git_repo(repo: "str | Path") -> bool:
    """Return True if *repo* is inside a valid git working tree, else print an error and return False."""
    import subprocess
    repo_path = Path(repo)
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--is-inside-work-tree"],
            cwd=str(repo_path),
            capture_output=True,
            text=True,
        )
        if proc.returncode == 0 and proc.stdout.strip() == "true":
            return True
    except (OSError, FileNotFoundError):
        pass
    print(
        f"Error: '{repo_path}' is not inside a valid git working tree.\n"
        "  The run-family commands require git to track changes and run governance checks.\n"
        "  To fix: run 'git init' in the directory, make a baseline commit, then retry.",
        file=sys.stderr,
    )
    return False


def _print_continuation_block(
    result: "RunResult",  # type: ignore[name-defined]
    output_dir: str,
    plan_path: str,
    repo_path: str,
    backend: str,
) -> None:
    """Print continuation / next step block after a run summary.

    Uses ledger-first approach: reads ``ledger.json`` from *output_dir* when
    available so that resume/rerun-failed/rerun-remaining runs (which return
    partial ``RunResult`` objects) still produce correct command suggestions.
    Falls back to ``RunResult`` ticket dispositions when the ledger is absent.
    """
    from saturnday.run.resume import (
        _select_continuation_command,
        describe_recovery_state,
        detect_recovered_baseline_state,
    )

    # Ledger-first: try to classify tickets from the on-disk ledger
    state: dict | None = None
    if output_dir:
        try:
            state = describe_recovery_state(output_dir)
        except Exception:
            pass

    if state is not None:
        failed: list[str] = state.get("failed", [])
        coded_ungoverned: list[str] = state.get("coded_ungoverned", [])
        skipped: list[str] = state.get("skipped", [])
        pending: list[str] = state.get("pending", [])
    else:
        # Fallback: derive from RunResult when ledger is unavailable
        failed = [tr.ticket_id for tr in result.ticket_results if tr.disposition == "FAIL"]
        coded_ungoverned = [
            tr.ticket_id for tr in result.ticket_results if tr.disposition == "CODED_UNGOVERNED"
        ]
        skipped = [tr.ticket_id for tr in result.ticket_results if tr.disposition == "SKIP"]
        pending = []

    # CODED_UNGOVERNED visibility warning
    if coded_ungoverned:
        print(
            f"\n  Warning: {len(coded_ungoverned)} ticket(s) were coded but governance "
            "did not clear them."
        )
        print("  Code is on the branch. saturnday resume will skip these tickets.")
        print("  Use saturnday rerun-failed to revisit them.")

    # Continuation command
    cmd_name = _select_continuation_command(failed, coded_ungoverned, skipped, pending)
    if cmd_name is None:
        return

    # Recovered-baseline detection: if all failures were git-state failures
    # and the repo is now a valid git working tree, the FAILed tickets may
    # already be materialised on disk via a manual baseline commit.
    # In that case resume (which re-runs those tickets) is the wrong step;
    # rerun-remaining (which targets only the unexecuted SKIP/PENDING tickets)
    # is correct.
    if cmd_name == "resume" and output_dir and repo_path:
        try:
            if detect_recovered_baseline_state(output_dir, repo_path):
                print(
                    "\n  Note: all prior failures were git-state failures — the coder ran "
                    "before a valid git working tree was available."
                )
                print(
                    "  The repo has since been baselined (git init + baseline commit)."
                )
                print(
                    "  Those failed tickets may already have their artefacts on disk."
                )
                print(
                    "  'saturnday resume' would re-run them unnecessarily. "
                    "Use 'saturnday rerun-remaining' to continue with the "
                    "still-unexecuted tickets instead."
                )
                cmd_name = "rerun-remaining"
        except Exception:
            pass

    evidence_dir_str = output_dir or "<output-dir>"
    plan_str = plan_path or "<plan>"
    repo_str = repo_path or "<repo>"
    backend_str = backend or "<backend>"

    print("\n  Next step:")
    print(
        f"    saturnday {cmd_name}"
        f" --output-dir {evidence_dir_str}"
        f" --plan {plan_str}"
        f" --repo {repo_str}"
        f" --backend {backend_str}"
    )


def _print_run_summary(  # type: ignore[name-defined]
    result: "RunResult",
    output_dir: str = "",
    plan_path: str = "",
    repo_path: str = "",
    backend: str = "",
) -> None:
    """Print a human-readable run summary."""
    print(f"\nPlan execution complete: {result.project_id}")
    print(f"  Passed:  {result.passed}/{result.total_tickets}")
    if result.coded_ungoverned > 0:
        print(f"  Coded (review needed): {result.coded_ungoverned}/{result.total_tickets}")
    print(f"  Failed:  {result.failed}/{result.total_tickets}")
    print(f"  Skipped: {result.skipped}/{result.total_tickets}")
    if result.definition_of_done_met:
        print("  Definition of done: MET")
    elif result.total_tickets > 0:
        print("  Definition of done: NOT MET")
    if result.stop_reason:
        print(f"  Stop reason: {result.stop_reason}")

    # Fix 39: surface verify_cmd failures prominently — executable proof of incomplete work.
    _vc_failures = [tr for tr in result.ticket_results if tr.verify_cmd_passed is False]
    if _vc_failures:
        print(f"  Executable verification FAILED: {len(_vc_failures)} ticket(s)")
        for _vcf in _vc_failures:
            summary = _vcf.verify_cmd_failure[:120] if _vcf.verify_cmd_failure else "see evidence"
            print(f"    [{_vcf.ticket_id}] verify_cmd failed — {summary}")

    # Fix 41: surface final acceptance gate result prominently.
    if result.acceptance_cmd_passed is True:
        print("  Final acceptance: PASSED")
    elif result.acceptance_cmd_passed is False:
        print("  Final acceptance: FAILED")
        if result.acceptance_cmd_failure:
            print(f"    {result.acceptance_cmd_failure[:200]}")

    # Fix 40: surface cross-ticket consistency failures prominently.
    if result.cross_ticket_consistency_failures:
        print(f"  Cross-ticket consistency FAILED: {len(result.cross_ticket_consistency_failures)} conflicting shared default(s)")
        for _ctcf in result.cross_ticket_consistency_failures:
            const = _ctcf.get("constant", "?")
            fa = _ctcf.get("file_a", "?")
            va = _ctcf.get("value_a", "?")
            fb = _ctcf.get("file_b", "?")
            vb = _ctcf.get("value_b", "?")
            print(f"    {const}: {fa!r}={va!r} vs {fb!r}={vb!r}")

    # Fix 39: surface plan-governance outcome with severity matching actual state.
    if result.plan_governance_reason:
        pg_label = "MET" if result.plan_governance_met else "NOT MET"
        print(f"  Plan governance: {pg_label}")
        if not result.plan_governance_met:
            print(f"  Reason: {result.plan_governance_reason}")

    for tr in result.ticket_results:
        status_icon = {"PASS": "+", "FAIL": "X", "SKIP": "-", "CODED_UNGOVERNED": "!"}.get(tr.disposition, "?")
        line = f"  [{status_icon}] {tr.ticket_id}: {tr.disposition}"
        if tr.error:
            line += f" — {tr.error[:80]}"
        print(line)

    # Print ungoverned ticket details with remediation tips
    ungoverned = [tr for tr in result.ticket_results if tr.disposition == "CODED_UNGOVERNED"]
    if ungoverned:
        print(f"\n  ⚠ {len(ungoverned)} ticket(s) coded but require review:\n")
        for tr in ungoverned:
            print(f"  {tr.ticket_id} — {len(tr.governance_findings)} governance finding(s):")
            for f in tr.governance_findings[:10]:
                kind = f.get("kind", f.get("message", "unknown"))
                file_path = f.get("file", f.get("path", ""))
                line_no = f.get("line", "")
                detail = f.get("detail", f.get("message", ""))
                loc = f"{file_path}:{line_no}" if line_no else file_path
                print(f"    {kind}: {loc}")
                if detail:
                    # One-liner remediation tip
                    tip = detail.split(".")[0] if "." in detail else detail
                    print(f"      → {tip[:100]}")
            if len(tr.governance_findings) > 10:
                print(f"    ... and {len(tr.governance_findings) - 10} more")
            print()
        # Point to review report and fix prompts if they exist
        if output_dir:
            review_md = Path(output_dir) / "review-required.md"
            prompts_dir = Path(output_dir) / "prompts"
            if review_md.is_file():
                print(f"  Review report: {review_md}")
            if prompts_dir.is_dir():
                print(f"  Fix prompts:   {prompts_dir}/")
                print("  Copy any prompt to Claude Code, Cursor, ChatGPT, or any AI coder.")
        print("\n  To re-check after fixing:")
        print("    saturnday governance --repo . --full")

    _print_continuation_block(result, output_dir, plan_path, repo_path, backend)


def _print_document_summary(result: "DocumentRunResult") -> None:  # type: ignore[name-defined]
    """Print a human-readable document run summary to stdout.

    Shows document_id, type, overall status, per-section outcome table,
    finding counts, claim summary, and sign-off status.

    Args:
        result: Completed :class:`~saturnday.document._types.DocumentRunResult`.
    """
    status_icon_map = {
        "PASS": "+",
        "WARN": "~",
        "FAIL": "X",
        "PROVISIONAL_UNVERIFIED": "?",
        "BLOCKED_FOR_SIGNOFF": "S",
        "APPROVED": "A",
        "REJECTED": "R",
    }
    icon = status_icon_map.get(result.document_status, "?")

    print(f"\nDocument run complete: {result.document_id}")
    print(f"  Type:       {result.type}")
    print(f"  Status:     [{icon}] {result.document_status}")
    print(f"  Sections:   {result.passed} passed / {result.failed} failed / {result.provisional} provisional")

    if result.sections:
        print("\n  Section outcomes:")
        for section in result.sections:
            s_icon = status_icon_map.get(section.status, "?")
            finding_count = len(section.findings)
            finding_note = f"  ({finding_count} finding(s))" if finding_count else ""
            print(f"    [{s_icon}] {section.section_id} — {section.name}: {section.status}{finding_note}")

    local_count = sum(len(s.findings) for s in result.sections)
    global_count = len(result.global_findings)
    print(f"\n  Findings:   {local_count} local, {global_count} global")

    if result.claims:
        verdicts: dict[str, int] = {}
        for claim in result.claims:
            v = claim.support_verdict or "(not verified)"
            verdicts[v] = verdicts.get(v, 0) + 1
        print(f"  Claims:     {len(result.claims)} extracted")
        for verdict, count in sorted(verdicts.items()):
            print(f"    {verdict}: {count}")

    if result.approvals:
        print(f"\n  Sign-offs:  {len(result.approvals)} recorded")
        for approval in result.approvals:
            print(f"    {approval.role} — {approval.status} by {approval.actor}")
    print()


def _warn_implicit_work_branch_default(command_name: str) -> None:
    """Closes Nick #3b — print a one-time-per-invocation deprecation
    banner when a governed-execution command runs without
    ``--work-branch``.

    Today, omitting ``--work-branch`` commits to whatever branch is
    currently checked out.  That default is unsafe (a misfired auto-
    commit lands on master/main).  The banner gives operators one
    minor-release window to migrate; in 1.2 the default flips so that
    omitting ``--work-branch`` implicitly behaves like
    ``--work-branch auto`` (a fresh saturnday/<command>-<timestamp>
    branch).  Operators can pin current behaviour by passing
    ``--work-branch <name-of-current-branch>`` (or, in 1.2, the
    explicit ``--no-work-branch``).

    Honour ``SATURNDAY_SUPPRESS_WORK_BRANCH_BANNER=1`` to silence the
    banner on CI / scripted invocations that have already been
    audited.
    """
    if os.environ.get("SATURNDAY_SUPPRESS_WORK_BRANCH_BANNER") == "1":
        return
    print(
        f"Saturnday: '{command_name}' is committing to the currently "
        f"checked-out branch.  In version 1.2, --work-branch auto will "
        f"become the default.  Pass --work-branch <name> to keep current "
        f"behaviour explicitly, or --work-branch auto to opt in now.  "
        f"Set SATURNDAY_SUPPRESS_WORK_BRANCH_BANNER=1 to silence this "
        f"warning.",
        file=sys.stderr,
        flush=True,
    )


def _cmd_run(args: argparse.Namespace) -> int:
    """Execute the ``run`` subcommand."""
    _configure_logging(args)
    if getattr(args, "work_branch", None) is None:
        _warn_implicit_work_branch_default("run")

    if os.environ.get("SATURNDAY_IN_SUBPROCESS"):
        print(
            "saturnday run: blocked — already running inside a Saturnday subprocess.\n"
            "Do not call 'saturnday run' from within a repair or run session.",
            flush=True,
        )
        return 1

    api_key = args.api_key or os.environ.get("SATURNDAY_CLOUD_API_KEY", "")
    if args.backend in ("openai", "anthropic") and not api_key:
        print(
            f"Error: --api-key or SATURNDAY_CLOUD_API_KEY is required for "
            f"backend '{args.backend}'.",
            file=sys.stderr,
        )
        return 1

    plan_path = Path(args.plan)
    if not plan_path.exists():
        print(f"Error: Plan file not found: {plan_path}", file=sys.stderr)
        return 1

    repo_path = Path(args.repo)
    if not repo_path.is_dir():
        print(f"Error: Repository not found: {repo_path}", file=sys.stderr)
        return 1
    if not _require_git_repo(repo_path):
        return 1

    # Fix A: bootstrap a ratchet baseline before any governed ticket runs so
    # pre-existing findings in touched files don't fail every ticket on a
    # dirty existing repo.  No-op when a baseline already exists.
    _bootstrap_baseline_if_missing(repo_path.resolve(), context="run")

    standards_dir = Path(args.standards_dir)
    if not standards_dir.is_dir():
        # Fallback: find the standards bundled with the saturnday package
        from .interactive import _find_standards_dir
        standards_dir = _find_standards_dir(repo_path)
        if not standards_dir.is_dir():
            print(f"Error: Standards directory not found: {args.standards_dir}", file=sys.stderr)
            return 1

    from ._types import CoderConfig
    config = CoderConfig(
        backend=args.backend,
        base_url=args.base_url or "",
        api_key=api_key,
        model=args.model or "",
        temperature=args.temperature,
        max_tokens=args.max_tokens,
        timeout_s=args.timeout,
    )

    from .ticket_runner import run_plan
    try:
        from saturnday.run.proof_questions import parse_proof_answer_flags
        _proof_answers = parse_proof_answer_flags(
            getattr(args, "proof_answer", None)
        )
        result = run_plan(
            plan_path=plan_path,
            repo_path=repo_path,
            coder_config=config,
            standards_dir=standards_dir,
            output_dir=args.output_dir,
            auto_repair=getattr(args, "auto_repair", False),
            lessons_db=getattr(args, "lessons", None),
            role_passes=not getattr(args, "no_role_passes", False),
            approve_acceptance_setup=getattr(args, "approve_acceptance_setup", False),
            work_branch=getattr(args, "work_branch", None),
            proof_answers=_proof_answers,
            max_consecutive_failures=getattr(args, "max_failures", None),
        )
    except Exception as exc:
        logger.error("Plan execution failed: %s", exc)
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    _print_run_summary(
        result,
        output_dir=args.output_dir or "",
        plan_path=str(plan_path),
        repo_path=str(repo_path),
        backend=getattr(args, "backend", "") or "",
    )

    # Print report path if generated
    if args.output_dir:
        report_path = Path(args.output_dir) / "run-report.md"
        if report_path.is_file():
            print(f"\nFull report: {report_path}")

    # --strict-dod: fail the process if the definition of done is not met
    if getattr(args, "strict_dod", False) and not result.definition_of_done_met:
        print(
            "Error: --strict-dod is set and the definition of done was NOT met.",
            file=sys.stderr,
        )
        return 1

    # Fix 39: plan-governance failure is a non-success signal even when all
    # tickets passed.  Only fires when a real evaluation happened (reason
    # non-empty) and the verdict is not the "no governance fields" sentinel.
    if (
        not result.plan_governance_met
        and result.plan_governance_reason
        and result.plan_governance_reason != "PLAN_GOVERNANCE_NO_GOVERNANCE"
    ):
        print(
            "Error: plan governance was NOT met — see 'Plan governance: NOT MET' above.",
            file=sys.stderr,
        )
        return 1

    # Fix 41: hard final acceptance gate — a failed acceptance_cmd is a
    # non-success signal regardless of ticket-level results.
    if result.acceptance_cmd_passed is False:
        print(
            "Error: final acceptance gate FAILED"
            " — the assembled product did not pass its acceptance command."
            " See 'Final acceptance: FAILED' above.",
            file=sys.stderr,
        )
        return 1

    # Fix 40: hard cross-ticket consistency gate — conflicting shared defaults
    # are a non-success signal regardless of per-ticket pass/fail counts.
    if result.cross_ticket_consistency_failures:
        print(
            "Error: cross-ticket consistency gate FAILED"
            " — conflicting shared defaults detected across files."
            " See 'Cross-ticket consistency FAILED' above.",
            file=sys.stderr,
        )
        return 1

    return 0 if result.failed == 0 else 1


