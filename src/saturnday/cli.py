def _cmd_plan(args: argparse.Namespace) -> int:
    """Execute the ``plan`` subcommand.

    When ``--doc-spec`` is provided, generates a document plan from the
    given doc-spec.yaml and exits.  The standard ``--brief`` code-plan path
    is used otherwise.
    """
    _configure_logging(args)

    if os.environ.get("SATURNDAY_IN_SUBPROCESS"):
        print(
            "saturnday plan: blocked — already running inside a Saturnday subprocess.\n"
            "Do not call 'saturnday plan' from within a repair or run session.",
            flush=True,
        )
        return 1

    # --- Document plan branch ---
    doc_spec_arg: str | None = getattr(args, "doc_spec", None)
    if doc_spec_arg:
        spec_path = Path(doc_spec_arg).resolve()
        if not spec_path.is_file():
            print(f"Error: doc-spec not found: {spec_path}", file=sys.stderr)
            return 1

        repo_path = Path(args.repo).resolve()

        try:
            from saturnday.document.spec_parser import parse_doc_spec, validate_doc_spec
            from saturnday.document.planner import generate_document_plan
        except ImportError as exc:
            print(f"Error: document module unavailable: {exc}", file=sys.stderr)
            return 1

        try:
            spec = parse_doc_spec(spec_path)
        except (ValueError, KeyError) as exc:
            print(f"Error: invalid doc-spec: {exc}", file=sys.stderr)
            return 1

        validation_errors = validate_doc_spec(spec, repo_path)
        if validation_errors:
            print("Error: doc-spec validation failed:")
            for err in validation_errors:
                print(f"  - {err}")
            return 1

        try:
            plan = generate_document_plan(spec, repo_path)
        except Exception as exc:
            logger.error("Document plan generation failed: %s", exc)
            print(f"Error: could not generate document plan: {exc}", file=sys.stderr)
            return 1

        plan_out = repo_path / ".saturnday" / "document" / "plan.json"
        print(f"Document plan generated: {plan.document_id}")
        print(f"  Sections: {len(plan.sections)}")
        print(f"  Plan file: {plan_out}")
        if getattr(args, "commit", False):
            print("  Note: --commit is not supported for document plans.", file=sys.stderr)
        return 0

    # --- Code plan branch (unchanged) ---
    if not getattr(args, "brief", None):
        print(
            "Error: --brief is required for code plan generation.\n"
            "For a document plan, use: saturnday plan --doc-spec doc-spec.yaml --repo .",
            file=sys.stderr,
        )
        return 1

    config = _build_coder_config(args)
    if config is None:
        return 1

    planner_config = None
    if getattr(args, "planner_backend", None):
        from ._types import CoderConfig
        api_key = args.api_key or os.environ.get("SATURNDAY_CLOUD_API_KEY", "")
        planner_config = CoderConfig(
            backend=args.planner_backend,
            base_url=args.base_url or "",
            api_key=api_key,
            model=args.planner_model or args.model or "",
            temperature=args.temperature,
            max_tokens=args.max_tokens,
            timeout_s=args.timeout,
        )

    # Fix 75: clarification gate runs BEFORE planning.  Detect ambiguity
    # triggers in the brief; refuse to proceed in non-interactive mode if
    # any blocking trigger is unanswered.
    from .run.clarification import (
        collect_clarifications,
        detect_ambiguity_triggers,
        format_refusal_message,
        parse_clarify_flags,
    )
    _cli_answers = parse_clarify_flags(getattr(args, "clarify", None))
    _triggers = detect_ambiguity_triggers(args.brief)
    _interactive = sys.stdin.isatty()
    _entries, _unanswered = collect_clarifications(
        _triggers,
        cli_answers=_cli_answers,
        interactive=_interactive,
    )
    if _unanswered:
        print(format_refusal_message(_unanswered), file=sys.stderr)
        return 1

    from .run.planner import generate_plan
    try:
        plan_path = generate_plan(
            brief=args.brief,
            repo_path=args.repo,
            coder_config=config,
            planner_config=planner_config,
            output_path=args.output,
            clarification_record=tuple(_entries),
        )
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:
        logger.error("Plan generation failed: %s", exc)
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    print(f"Plan generated: {plan_path}")
    if not args.output:
        print("  (Default output: .saturnday/plan.json. Use --output to write elsewhere.)")

    # Opt-in commit with normal hook verification
    if getattr(args, "commit", False):
        import subprocess as _sp_plan
        repo = Path(args.repo).resolve()
        try:
            _sp_plan.run(
                ["git", "-C", str(repo), "add", str(plan_path)],
                capture_output=True, timeout=10, check=True,
            )
            _sp_plan.run(
                ["git", "-C", str(repo), "commit", "-m", "saturnday: plan generated"],
                capture_output=True, timeout=30, check=True,
            )
            print("  Plan committed to git.")
        except _sp_plan.CalledProcessError as exc:
            print(f"  Warning: git commit failed: {exc}", file=sys.stderr)
        except Exception as exc:
            print(f"  Warning: could not commit plan: {exc}", file=sys.stderr)

    return 0


